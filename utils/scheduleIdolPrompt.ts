import type { CharacterProfile } from '../types';

/** 只对角色卡本身属于演艺/偶像身份的角色启用，不干扰其他世界观。 */
const IDOL_CARD_MARKERS = /时代少年团|时代峰峻|偶像团体|男团|女团|爱豆|偶像歌手|艺人|idol/iu;

export function buildIdolScheduleVariationPrompt(char: Pick<CharacterProfile, 'systemPrompt'>): string {
    if (!IDOL_CARD_MARKERS.test(char.systemPrompt || '')) return '';
    return [
        '【爱豆日常｜有自己的生活，也有临时变化】',
        '结合这张角色卡写他的真实职业分工、个人资源、成员关系和生活习惯：团体排练、舞台准备、录音棚、拍摄物料/商务、综艺或个人外务、妆发候场与往返通勤按需要出现；哪种工作属于谁，由人设决定，别让所有成员每天做相同的事。没有已知工作的日子可以休息，不必硬排通告。',
        '私下也要过日子：补觉、运动、遛狗或照顾宠物（只在角色设定里确实有时）、打游戏、散步、看电影、做饭、探店、逛街、和成员朋友相处或独处。私人活动依这个人真实的偏好选择，不每天固定「训练—健身—洗澡—睡觉」四件套。',
        '用晨起、出发、工作/主任务、午间休整、下午工作、傍晚转换、夜间消遣、入寝这些生活功能去组织5—7个时段，不必逐项写齐或把每个时段塞满；有忙碌的拍摄日，也有平静的空档日。通告日可有等待、转场或临时收工，休息日不用假装每天都在营业。',
        '通常（约八成）沿着本人习惯安排一天，偶尔（约两成）仅让1—2个时段发生自然的小变化；变化要真正换掉原来要做的事，而非把整天时间整体后移。可来自被动小扰动、自己临时改变主意、天气场地等客观条件、成员朋友或对方的临时邀约。不要为了求变化强行制造事故、重伤、倒霉连锁或无故毁约。',
        '已在聊天和记忆中确定的今天约会、工作与承诺优先。和对方约好下午逛街，就把可调整的私人健身改成逛街；如撞上明确不可取消的工作，应自然协商时间，不假装工作不存在。只是提议但尚未确定的约会，不提前写成已发生的事实。',
        '日程是角色世界里的初步私人计划，不是现实艺人的官方公开行程；不要凭空宣布具体活动、商务品牌、航班、节目录制时间或与对方共同发生过的往事。变化受人设和世界观约束，保留角色独立生活。',
    ].join('\n');
}
