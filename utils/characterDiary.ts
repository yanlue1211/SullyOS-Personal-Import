/** Used only for an explicit diary generation request, never ordinary chat. */
export function characterDiaryInstructions(independent: boolean, date: string): string {
  return `本次任务：${independent ? `以角色自己的第一人称写 ${date} 的个人日记，不是给用户的回信，不需要用户先写日记。` : `阅读用户 ${date} 的日记，以角色口吻写回复日记，回应具体内容，同时分享自己的生活。`}
文风完全服从角色性格、年龄、口头习惯和当时心情：活泼的人可以跳跃、吐槽、碎碎念、用感叹号；克制的人可以简洁内敛；不把所有人写成成熟、温柔、文艺的散文作者。不强行诗意化、总结人生或升华感情，避免“平凡而珍贵”“这一刻我明白了”等模板结尾。
通常写约400–700个汉字，分成自然段，具体且比简短便签更充分；素材少时可短一些，情绪丰富时可稍长，不靠重复、空泛感悟凑字数。可以写琐事、未说出口的反应、跳跃联想和自己的关注点，不必每段围绕用户，不默认恋爱关系。
已知经历依据下方记录。没有记录支持的生活片段只能作为符合设定的虚构补充，不能捏造用户的行动、共同经历、购买或已完成事件；不要把当天日程里的计划直接写成已发生事实。过往日期不得混入之后发生的聊天。
${independent ? '用户可能读到这篇日记，但正文仍是写给自己的，不要写成回复用户的话。' : '对用户的回应与自己的生活自然融合，不机械逐条作答。'}`;
}
